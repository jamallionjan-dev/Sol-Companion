"""s84 address_places (Jamal 2026-11-10 23:07: he read the "Coalfield, Kentucky - A Taste of the Wild West" brochure and seven other
papers in front of Sol, and her book kept only the two house listings and the map). Every paper or map that shows a place on the
world map is learned: houses for sale, attractions, shops, public places (with stashes and revealed areas as before), and "our home"
pinned at the top. Game closed only. In place and idempotent.

  copies   SolAddressPlaces.lua      (generated ASCII from src/SolAddressPlaces_src.lua)  -> <client dir>
           SolAddressPlacesData.lua  (generated from 05_TOOLS/sol_mind/gazetteer.json.gz: towns, landmarks, named buildings)
  edits    SolAddressBook.lua        one anchor: a row may carry its own kind line (r.kindTxt) - nil keeps the old line
           SolAuthority.lua          A.FIXES += "address_places"
           <Zomboid>/Lua/SolFixes_LAB.txt  address_places=on (only when missing)
Runtime wraps (no anchors): SolAddressBook.onPrintMedia and .rows, SolAddressTarget.target (s82, when present). s82's own wrap of
SolAddressBook.go is not touched, so the two installers apply in either order.
Needs (installed in the lab): SolAddressBook.lua (address_book). Uses SolAddressTarget.lua (address_target) and SolHome.lua when present.
usage: apply_s84_address_places.py <client dir>
       apply_s84_address_places.py --gen      regenerate both Lua files"""
import gzip, json, os, shutil, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
NL, CRLF = chr(10), chr(13) + chr(10)
FIX = "address_places"
NAME, DATA = "SolAddressPlaces.lua", "SolAddressPlacesData.lua"
GAZ = os.path.join(ROOT, "05_TOOLS", "sol_mind", "gazetteer.json.gz")
ANCHOR_OLD = 'local kindTxt = e.kind == "house" and'
ANCHOR_NEW = 'local kindTxt = r.kindTxt or e.kind == "house" and'          # address_places: the row's own kind line first


def q(s):
    s = str(s)
    assert all(ord(c) < 128 for c in s), s                    # the map's names are ASCII
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen():
    src = open(os.path.join(HERE, "src", "SolAddressPlaces_src.lua"), encoding="utf-8").read()
    out = "".join(c if ord(c) < 128 else "\\\\u%04X" % ord(c) for c in src)
    open(os.path.join(HERE, NAME), "w", encoding="ascii", newline="\n").write(out)
    d = json.load(gzip.open(GAZ, "rt", encoding="utf-8"))
    lines = ["-- SolAddressPlacesData.lua - address_places. GENERATED by apply_s84_address_places.py --gen from 05_TOOLS/sol_mind/gazetteer.json.gz",
             "-- (the map's own towns, landmarks and named buildings; read once from the game's map files). Data only.",
             "SolAddressPlacesData = {", "    towns = {"]
    for t in d["towns"]:
        r = t["r"][0] if t["r"] else None
        box = (", x1 = %d, y1 = %d, x2 = %d, y2 = %d" % (r[0], r[1], r[0] + r[2], r[1] + r[3])) if r else ""
        lines.append("        { n = %s, x = %d, y = %d%s }," % (q(t["n"]), t["x"], t["y"], box))
    lines += ["    },", "    named = {"]
    seen = set()
    for b in d["buildings"]:
        if len(b) > 5 and b[5] >= 0:
            n = d["names"][b[5]]
            if n in seen: continue
            seen.add(n)
            lines.append("        { n = %s, x = %d, y = %d, x1 = %d, y1 = %d, x2 = %d, y2 = %d }," % (q(n), (b[0] + b[2]) // 2, (b[1] + b[3]) // 2, b[0], b[1], b[2], b[3]))
    for l in d["landmarks"]:
        if l["n"] in seen: continue
        seen.add(l["n"])
        lines.append("        { n = %s, x = %d, y = %d }," % (q(l["n"]), l["x"], l["y"]))
    lines += ["    },", "}", "return SolAddressPlacesData", ""]
    open(os.path.join(HERE, DATA), "w", encoding="ascii", newline="\n").write(NL.join(lines))
    print("generated", NAME, DATA, "(%d named places)" % len(seen))


def edit(path, old, new, done_marker):
    t = open(path, encoding="utf-8", newline="").read()
    if done_marker in t: return "kept"
    nl = CRLF if CRLF in t else NL
    old, new = old.replace(NL, nl), new.replace(NL, nl)
    assert t.count(old) == 1, (os.path.basename(path), t.count(old), old[:90])
    open(path, "w", encoding="utf-8", newline="").write(t.replace(old, new))
    return "edited"


def client(cl):
    for need in ("SolAuthority.lua", "SolAddressBook.lua"):
        assert os.path.isfile(os.path.join(cl, need)), "not a Sol client dir with %s: %s" % (need, cl)
    for name, mark in ((NAME, 'M.VERSION = "0.1.0"'), (DATA, "SolAddressPlacesData = {")):
        src = os.path.join(HERE, name)
        body = open(src, encoding="ascii").read()
        assert mark in body, name
        dst = os.path.join(cl, name)
        if os.path.exists(dst) and open(dst, encoding="ascii").read() == body: print("kept", name)
        else: shutil.copy(src, dst); print("copied", name)
    print("SolAddressBook", edit(os.path.join(cl, "SolAddressBook.lua"), ANCHOR_OLD, ANCHOR_NEW, "r.kindTxt or"))
    print("SolAuthority", edit(os.path.join(cl, "SolAuthority.lua"), "A.FIXES = {" + NL,
          "A.FIXES = {" + NL + '    "%s",     -- every paper or map with a place goes into her book, by kind; our home at the top' % FIX + NL, '"%s"' % FIX))
    fixfile = os.path.join(cl, "..", "..", "..", "..", "..", "..", "Lua", "SolFixes_LAB.txt")
    if os.path.exists(fixfile):
        have = open(fixfile, encoding="utf-8").read()
        if FIX + "=" not in have:
            with open(fixfile, "a", encoding="utf-8", newline="") as h:
                if have and not have.endswith(NL): h.write(CRLF)
                h.write(FIX + "=on" + CRLF)
            print("SolFixes_LAB", FIX + "=on")


if __name__ == "__main__":
    if sys.argv[1:] == ["--gen"]: gen()
    else:
        client(sys.argv[1])
        print("s84 address_places applied")
