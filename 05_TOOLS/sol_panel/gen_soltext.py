"""Build the SolText glyph set: one white PNG per glyph + a Lua data file with advances and the
Arabic shaping table (base letter -> isolated/final/initial/medial presentation forms)."""
import os, unicodedata, math
from PIL import Image, ImageDraw, ImageFont
OUT_TEX = "build/media/textures/SolText"
OUT_LUA = "build/media/lua/client/SolTextData.lua"
os.makedirs(OUT_TEX, exist_ok=True); os.makedirs(os.path.dirname(OUT_LUA), exist_ok=True)
SIZE = 30; PAD = 3
AR = ImageFont.truetype("/home/claude/fonts/IBMPlexSansArabic-SemiBold.ttf", SIZE, layout_engine=ImageFont.Layout.BASIC)
LA = ImageFont.truetype("/home/claude/fonts/IBMPlexSansArabic-SemiBold.ttf", SIZE, layout_engine=ImageFont.Layout.BASIC)
try: LA.set_variation_by_axes([500, 100]); AR.set_variation_by_axes([500, 100])
except Exception: pass
a1, d1 = AR.getmetrics(); a2, d2 = LA.getmetrics()
ASC, DESC = max(a1, a2), max(d1, d2)
LH = ASC + DESC; BASE = ASC
# --- shaping table from Unicode names
forms = {}; ligs = {}
for cp in range(0xFE70, 0xFF00):
    try: n = unicodedata.name(chr(cp))
    except ValueError: continue
    for kind in ("ISOLATED", "FINAL", "INITIAL", "MEDIAL"):
        suf = " %s FORM" % kind
        if n.endswith(suf) and n.startswith("ARABIC LETTER "):
            try: base = ord(unicodedata.lookup(n[:-len(suf)]))
            except KeyError: continue
            forms.setdefault(base, {})[kind[:3].lower()] = cp
        if n.endswith(suf) and n.startswith("ARABIC LIGATURE LAM WITH ALEF"):
            alef = n[len("ARABIC LIGATURE LAM WITH "):-len(suf)]
            try: a = ord(unicodedata.lookup("ARABIC LETTER " + alef))
            except KeyError: continue
            ligs.setdefault(a, {})[kind[:3].lower()] = cp
glyphs = set(range(0x20, 0x7F)) | set(range(0x660, 0x66A)) | {0x60C, 0x61B, 0x61F, 0x66A, 0x640, 0x2026, 0xAB, 0xBB, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0xB0, 0xD7}
for f in forms.values(): glyphs |= set(f.values())
for f in ligs.values(): glyphs |= set(f.values())
adv = {}
def font_for(cp): return AR if (0x600 <= cp <= 0x6FF or cp >= 0xFB50) else LA
for cp in sorted(glyphs):
    ch = chr(cp); f = font_for(cp)
    if cp != 0x20 and not f.getmask(ch).getbbox():
        if f is AR and LA.getmask(ch).getbbox(): f = LA
        else: continue
    a = f.getlength(ch); adv[cp] = round(a, 2)
    if cp == 0x20: continue
    w = int(math.ceil(a)) + 2 * PAD
    im = Image.new("L", (w * 2, LH * 2), 0); d = ImageDraw.Draw(im)
    big = ImageFont.truetype(f.path, SIZE * 2, layout_engine=ImageFont.Layout.BASIC)
    try: big.set_variation_by_axes([500, 100])
    except Exception: pass
    d.text((PAD * 2, BASE * 2), ch, font=big, fill=255, anchor="ls")
    m = im.resize((w, LH), Image.LANCZOS)
    rgba = Image.new("RGBA", (w, LH), (255, 255, 255, 0)); rgba.putalpha(m)
    rgba.save(os.path.join(OUT_TEX, "g%04X.png" % cp), optimize=True)
def lt(d): return "{" + ", ".join("[%d]=%s" % (k, v) for k, v in sorted(d.items())) + "}"
# Kahlua (the game's Lua) gives one Java char per string position, but string.byte() returns only the low
# 8 bits (proven in game 2026-10-23: Arabic shown as 'D-'D)). So decoding uses a lookup: this literal string,
# read char by char with string.sub, maps each char to its code point.
def assigned(c):
    try: unicodedata.name(chr(c)); return True
    except ValueError: return False
cmap_cps = [c for c in list(range(0xA0, 0x100)) + list(range(0x600, 0x700)) + list(range(0xFB50, 0xFE00)) + list(range(0xFE70, 0xFF00))
            + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x200C, 0x200D, 0x200E, 0x200F]
            if assigned(c) and unicodedata.category(chr(c)) not in ("Cc", "Cs", "Co")]
lines_cmap = "".join(chr(c) for c in cmap_cps)
lines = ["-- generated by gen_soltext.py (Noto Sans Arabic / Noto Sans, %dpx). Do not edit." % SIZE,
         "SolTextData = { size = %d, lh = %d, base = %d, pad = %d," % (SIZE, LH, BASE, PAD),
         "  adv = " + lt(adv) + ",",
         "  forms = {" + ", ".join("[%d]={iso=%s,fin=%s,ini=%s,med=%s}" % (b, f.get("iso", "nil"), f.get("fin", "nil"), f.get("ini", "nil"), f.get("med", "nil")) for b, f in sorted(forms.items())) + "},",
         "  lamalef = {" + ", ".join("[%d]={iso=%s,fin=%s}" % (a, f.get("iso", "nil"), f.get("fin", "nil")) for a, f in sorted(ligs.items())) + "},",
         "}"]
open(OUT_LUA, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("glyphs:", len([n for n in os.listdir(OUT_TEX)]), "letters:", len(forms), "lamalef:", len(ligs), "LH:", LH, "BASE:", BASE)
